"""True phase damping sweep, purifier check and residual attribution (SYNTHETIC EXPERIMENT).

Does not change the published model. Usage:
    python -m experiments.run_phase_damping [--write]
Seeds 3000-3099 (sweep, micro-measurement) and 3000-3039 (attribution) are
disjoint from the dev, confirm, tuning and pilot seeds of the injection analysis.
Writes experiments/results/phase_damping.json and phase_damping.md with --write.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import sys
from concurrent.futures import ProcessPoolExecutor

import numpy as np

from experiments import stats
from experiments.injection_runs import RESULTS_DIR
from experiments.phase_damping import TERMS, attribute_step, off_diagonal_damping, phase_damped_arena
from membrane_arena_3x3.core import apply_dephasing, normalized_entropy
from membrane_arena_3x3.engine import EngineConfig, MembraneArena3x3
from membrane_arena_3x3.lattice import LatticeConfig

SWEEP_SEEDS = tuple(range(3000, 3100))
ATTR_SEEDS = tuple(range(3000, 3040))
GAMMAS = (0.0, 0.1, 0.25, 0.5, 1.0, 2.0)  # lattice.dephasing; dissipative rate is gamma * dt per step
KINDS = ("published", "true_phase_damping")


def _config(seed: int, gamma: float) -> EngineConfig:
    return EngineConfig(steps=200, seed=seed, lattice=LatticeConfig(dephasing=gamma))


def sweep_job(args):
    kind, gamma, seed = args
    eng = phase_damped_arena(_config(seed, gamma)) if kind == "true_phase_damping" else MembraneArena3x3(_config(seed, gamma))
    s = eng.run()
    last_reason = eng.calibrations[-1]["reason"] if eng.calibrations else "none"
    return {
        "kind": kind, "gamma": gamma, "seed": seed, "steps": s["steps_executed"], "accepted": s["accepted_steps"],
        "status": s["status"], "latch_reason": last_reason if s["status"] == "circuit_breaker_open" else "no_latch",
        "final_min_purity": s["final"].get("min_purity"), "final_mean_entropy": s["final"].get("mean_entropy"),
        "final_max_divergence": s["final"].get("max_divergence"), "final_max_residual": s["final"].get("max_residual"),
    }


def attribution_job(seed: int):
    """Attribute the residual growth at every step up to and including the first rejection."""
    eng = MembraneArena3x3(_config(seed, 0.5))
    rows = []
    for _ in range(40):
        state0 = eng.lattice.state.copy()
        step_index = eng.current_step
        res = eng.step()
        if res["status"] == "circuit_breaker_open":
            break
        signal = eng.calibrations[-1]["total_signal"]
        saved = eng.lattice.state
        eng.lattice.state = state0  # attribute at the pre-step state, then restore
        try:
            rows.append({"step": step_index + 1, "accepted": res["status"] == "accepted", **attribute_step(eng.lattice, signal)})
        finally:
            eng.lattice.state = saved
        if res["status"] != "accepted":
            break  # later steps retry the identical proposal
    return {"seed": seed, "rows": rows}


def micro_job(seed: int):
    """One dissipative application at the stock rate on the seed's nine initial cells, both kinds."""
    eng = MembraneArena3x3(_config(seed, 0.5))
    g = 0.5 * eng.config.lattice.dt
    out = {"seed": seed}
    for kind, fn in (("published", apply_dephasing), ("true_phase_damping", off_diagonal_damping)):
        dp, dh, dpop = [], [], []
        for i in range(3):
            for j in range(3):
                rho = eng.lattice.state[i, j]
                new = fn(rho, g)
                if kind == "true_phase_damping":
                    new = new / np.trace(new).real
                dp.append(np.trace(new @ new).real - np.trace(rho @ rho).real)
                dh.append(normalized_entropy(new) - normalized_entropy(rho))
                dpop.append(float(np.abs(np.diag(new).real - np.diag(rho).real).sum()))
        out[kind] = {"dpurity": float(np.mean(dp)), "dentropy": float(np.mean(dh)), "population_shift_l1": float(np.mean(dpop))}
    return out


def ci(x):
    e = stats.paired_effect(np.asarray(x, dtype=float))
    return e["mean"], e["mean_ci"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    with ProcessPoolExecutor() as pool:
        sweep = list(pool.map(sweep_job, [(k, g, s) for k in KINDS for g in GAMMAS for s in SWEEP_SEEDS], chunksize=4))
        attr = list(pool.map(attribution_job, ATTR_SEEDS, chunksize=1))
        micro = list(pool.map(micro_job, SWEEP_SEEDS, chunksize=4))

    L = ["# True phase damping experiment (SYNTHETIC EXPERIMENT; generated by experiments/run_phase_damping.py)", "",
         f"Python {platform.python_version()}, NumPy {np.__version__}. The published model is unchanged; only the dissipative term is swapped in the experiment arm. Stock engine, no injection. Seeds {SWEEP_SEEDS[0]} to {SWEEP_SEEDS[-1]} (sweep), {ATTR_SEEDS[0]} to {ATTR_SEEDS[-1]} (attribution).", "",
         "## Sweep over gamma (`dephasing`; rate per step is gamma * dt), 100 seeds per cell", "",
         "Paired by seed: both arms start from identical states and Hamiltonians. Difference = true damping minus published.", "",
         "| gamma | arm | mean steps [95% CI] | mean accepted [95% CI] | breaker open | latch reasons | mean final min purity |", "|---|---|---|---|---|---|---|"]
    summary = {"sweep": {}, "diff": {}}
    for g in GAMMAS:
        for k in KINDS:
            rows = [r for r in sweep if r["kind"] == k and r["gamma"] == g]
            st, stc = ci([r["steps"] for r in rows]); ac, acc = ci([r["accepted"] for r in rows])
            lat = {}
            for r in rows:
                lat[r["latch_reason"]] = lat.get(r["latch_reason"], 0) + 1
            opened = sum(1 for r in rows if r["status"] == "circuit_breaker_open")
            mp = float(np.mean([r["final_min_purity"] for r in rows]))
            summary["sweep"][f"{k}@{g}"] = {"steps": st, "steps_ci": stc, "accepted": ac, "accepted_ci": acc, "breaker_open": opened, "latch": lat, "min_purity": mp}
            L.append(f"| {g} | {k} | {st:.1f} [{stc[0]:.1f}, {stc[1]:.1f}] | {ac:.1f} [{acc[0]:.1f}, {acc[1]:.1f}] | {opened}/{len(rows)} | {lat} | {mp:.3f} |")
    L += ["", "Paired difference (true damping minus published), accepted steps:", "", "| gamma | mean difference [95% CI] | dz |", "|---|---|---|"]
    for g in GAMMAS:
        a = {r["seed"]: r["accepted"] for r in sweep if r["kind"] == "published" and r["gamma"] == g}
        b = {r["seed"]: r["accepted"] for r in sweep if r["kind"] == "true_phase_damping" and r["gamma"] == g}
        d = [b[s] - a[s] for s in SWEEP_SEEDS]
        e = stats.paired_effect(d)
        summary["diff"][str(g)] = e
        dz = "n/a" if e["dz"] is None else f"{e['dz']:.2f}"
        L.append(f"| {g} | {e['mean']:.2f} [{e['mean_ci'][0]:.2f}, {e['mean_ci'][1]:.2f}] | {dz} |")

    L += ["", "## Is the published dephasing term a purifier? One application at the stock rate (gamma 0.5, dt 0.05), nine initial cells per seed", "",
          "Mean change per cell after one application (95% bootstrap CI over 100 seeds). Positive purity change and negative entropy change mean the state became purer. Population shift is the L1 change of the diagonal.", "",
          "| arm | change in purity | change in normalized entropy | population shift (L1) |", "|---|---|---|---|"]
    summary["micro"] = {}
    for k in KINDS:
        cells = []
        for key in ("dpurity", "dentropy", "population_shift_l1"):
            m, c = ci([x[k][key] for x in micro])
            cells.append(f"{m:.5f} [{c[0]:.5f}, {c[1]:.5f}]")
            summary["micro"].setdefault(k, {})[key] = [m, c]
        L.append(f"| {k} | " + " | ".join(cells) + " |")

    L += ["", "## Attribution of residual growth by term (published model, stock parameters, 40 seeds)", "",
          "Method (see `attribute_step` in experiments/phase_damping.py): at each step up to and including the first rejection, R is the largest residual over the nine cells. `alone` = R of the candidate built from that term only (then the stock projection and mirror) minus R now; `null_mirror_only` is the same with no term at all (projection and mirror on the unchanged state) and `alone_net` = alone minus null; `leave-out` = R(full candidate) minus R(candidate without the term); the mirror effect = R(full) minus R(full with the mirror off). Per-seed means over steps, then mean and 95% bootstrap CI over seeds. Terms interact through projection and mirror, so alone and leave-out need not add up. Units: residual (infinity norm).", "",
          "| quantity | all steps: mean [95% CI] | step 1 only: mean [95% CI] |", "|---|---|---|"]
    keys = ["growth_full", "null_mirror_only"] + [f"alone_{t}" for t in TERMS] + [f"alone_net_{t}" for t in TERMS] + [f"leave_out_{t}" for t in TERMS] + ["mirror_effect"] + [f"dpurity_alone_{t}" for t in TERMS] + ["dpurity_mirror"]
    summary["attribution"] = {}
    for key in keys:
        per_seed = [np.mean([r[key] for r in a["rows"]]) for a in attr if a["rows"]]
        first = [a["rows"][0][key] for a in attr if a["rows"]]
        m, c = ci(per_seed); m1, c1 = ci(first)
        summary["attribution"][key] = {"all": [m, c], "first": [m1, c1]}
        L.append(f"| {key} | {m:.5f} [{c[0]:.5f}, {c[1]:.5f}] | {m1:.5f} [{c1[0]:.5f}, {c1[1]:.5f}] |")
    n_steps = [len(a["rows"]) for a in attr]
    L += ["", f"Steps attributed per seed: mean {np.mean(n_steps):.1f} (min {min(n_steps)}, max {max(n_steps)}).", ""]
    text = "\n".join(L)
    print(text)
    if args.write:
        with open(os.path.join(RESULTS_DIR, "phase_damping.md"), "w", encoding="utf-8") as fh:
            fh.write(text)
        with open(os.path.join(RESULTS_DIR, "phase_damping.json"), "w", encoding="utf-8") as fh:
            json.dump({"summary": summary, "sweep_rows": sweep}, fh, indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
