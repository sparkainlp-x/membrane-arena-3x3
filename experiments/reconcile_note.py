"""Reconcile the design note's numbers with the merged injection engine (SYNTHETIC).

The note's table (seeds 42, 0, 1, 2, 3; 200 steps requested; commit 0.75) and
its totals (-1215 at commit 0.75, +68 at commit 0.35) differed from the merged
engine. Two differences are tested here, each separately and together:

  RNG    merged: numpy.random.default_rng([seed, 0xC4157A11])
         note:   numpy.random.default_rng(seed + 10_000_007)
  SCORE  merged: sum over every variant tried of points(p_k, passed_k)
         note:   per event, 0.5 * points(first commit, event outcome)
                 + 0.5 * points(last commit, event outcome) - 0.8 * variants tried

After the engine was aligned to the author's original, the engine's default
stream IS the note's stream and its ledger IS the two-forecast scoring. "merged"
below therefore means the historical (pre-alignment) engine: its stream is set
explicitly in ``run`` and its scoring is the offline per-attempt rescoring.
Neither changes a guard or the acceptance rule. Usage:
    python -m experiments.reconcile_note [--write]
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np

from experiments import rescoring as rs
from experiments.injection_runs import RESULTS_DIR
from experiments.regimes import REGIMES
from membrane_arena_3x3.crystallize_injection import InjectionConfig, MembraneArena3x3WithInjection

SEEDS = (42, 0, 1, 2, 3)
# Values as printed in the design note (steps executed / accepted, injection passes, score at commit 0.75).
NOTE_TABLE = {42: (11, 6, 3, -184.7), 0: (10, 5, 1, -333.1), 1: (10, 5, 2, -269.9), 2: (11, 6, 3, -184.7), 3: (11, 6, 2, -242.5)}
NOTE_TOTALS = {"0.75": -1215.0, "0.35": 68.0}
# Evolved-genome claims in the note (seed 42): 55 events, 50 passes, fixed 0.35 score, adaptive score and final commit.
NOTE_EVOLVED = {"events": 55, "passes": 50, "fixed_0.35": -3288.2, "adaptive_0.35": 3459.2, "adaptive_final": 0.87}


def run(regime: str, seed: int, rng: str, **inj):
    reg = REGIMES[regime]
    eng = MembraneArena3x3WithInjection(
        reg.engine_config(seed),
        InjectionConfig(first_factor=reg.first_factor, mirror_variant=reg.mirror_variant, **inj),
    )
    if rng == "merged":  # historical pre-alignment stream, set explicitly
        eng.injection_rng = np.random.default_rng([seed, 0xC4157A11])
    elif rng == "note":
        eng.injection_rng = np.random.default_rng(seed + eng.injection.seed_offset)
    s = eng.run()
    ev = [[len(e["attempts"]), bool(e["passed"])] for e in eng.injections]
    return s, ev


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    L = ["# Reconciliation with the design note (SYNTHETIC; generated by experiments/reconcile_note.py)", ""]

    L += ["## Note table, commit 0.75, stock parameters", "",
          "Each cell is `steps / accepted, passes, score`. The last column is the note's printed row.", "",
          "| seed | merged RNG, merged score | merged RNG, note score | note RNG, merged score | note RNG, note score | note |", "|---|---|---|---|---|---|"]
    match = {("merged", "per_attempt"): 0, ("merged", "two"): 0, ("note", "per_attempt"): 0, ("note", "two"): 0}
    totals = {k: 0.0 for k in match}
    for seed in SEEDS:
        cells = []
        for rng in ("merged", "note"):
            s, ev = run("stock", seed, rng, first_commit=0.75)
            firsts = rs.policy_first_commits(ev, {"kind": "fixed", "p": 0.75})
            for sc, fn in (("per_attempt", rs.ledger_per_attempt), ("two", rs.ledger_two_forecast)):
                sc_val = fn(ev, firsts)
                totals[(rng, sc)] += sc_val
                key = (s["steps_executed"], s["accepted_steps"], s["injection_passes"], round(sc_val, 1))
                match[(rng, sc)] += key == NOTE_TABLE[seed]
                cells.append((rng, sc, f"{s['steps_executed']} / {s['accepted_steps']}, {s['injection_passes']}, {sc_val:.1f}"))
        order = {("merged", "per_attempt"): 0, ("merged", "two"): 1, ("note", "per_attempt"): 2, ("note", "two"): 3}
        cells.sort(key=lambda c: order[(c[0], c[1])])
        n = NOTE_TABLE[seed]
        L.append(f"| {seed} | " + " | ".join(c[2] for c in cells) + f" | {n[0]} / {n[1]}, {n[2]}, {n[3]} |")
    L += ["", "Rows matching the note exactly (steps, accepted, passes, score to one decimal), out of 5:", ""]
    for (rng, sc), k in match.items():
        L.append(f"- {rng} RNG with {'merged per-attempt' if sc == 'per_attempt' else 'note two-forecast'} scoring: {k} of 5 (total score {totals[(rng, sc)]:.1f})")
    L.append("")

    L += ["## Note totals over the five seeds (two-forecast scoring)", "", "| commit | note total | merged RNG | note RNG |", "|---|---|---|---|"]
    for p in (0.75, 0.35):
        tot = {}
        for rng in ("merged", "note"):
            t = 0.0
            for seed in SEEDS:
                s, ev = run("stock", seed, rng, first_commit=p)
                t += rs.ledger_two_forecast(ev, rs.policy_first_commits(ev, {"kind": "fixed", "p": p}))
            tot[rng] = t
        L.append(f"| {p} | {NOTE_TOTALS[str(p)]:.0f} | {tot['merged']:.1f} | {tot['note']:.1f} |")
    L.append("")

    L += ["## Evolved genome, seed 42 (note: 55 events, 50 passes, fixed 0.35 = -3288.2, adaptive from 0.35 = +3459.2, final commit 0.87)", "",
          "| RNG | scoring | events | passes | fixed 0.35 | adaptive from 0.35 | adaptive final commit | steps / accepted |", "|---|---|---|---|---|---|---|---|"]
    for rng in ("merged", "note"):
        s, ev = run("evolved", 42, rng, first_commit=0.35)
        f35 = rs.policy_first_commits(ev, {"kind": "fixed", "p": 0.35})
        a35 = rs.policy_first_commits(ev, {"kind": "adaptive", "first": 0.35, "weight": 4})
        passes = sum(1 for _, p in ev if p)
        final = (passes + 4 * 0.35) / (len(ev) + 4)
        for sc, fn in (("per-attempt", rs.ledger_per_attempt), ("two-forecast", rs.ledger_two_forecast)):
            L.append(f"| {rng} | {sc} | {len(ev)} | {passes} | {fn(ev, f35):.1f} | {fn(ev, a35):.1f} | {final:.3f} | {s['steps_executed']} / {s['accepted_steps']} |")
    L += ["", "Held-out seed 1 (note: 50 accepted of 55 executed):", "", "| RNG | steps / accepted |", "|---|---|"]
    for rng in ("merged", "note"):
        s, _ = run("evolved", 1, rng, first_commit=0.35)
        L.append(f"| {rng} | {s['steps_executed']} / {s['accepted_steps']} |")
    L.append("")

    L += ["## Is the RNG stream choice immaterial? 40 dev seeds (1000 to 1039), both streams, per regime", "",
          "| regime | stream | mean steps | mean accepted | pass rate |", "|---|---|---|---|---|"]
    for reg in REGIMES:
        for rng in ("merged", "note"):
            st = ac = ev_n = ps = 0
            for seed in range(1000, 1040):
                s, ev = run(reg, seed, rng, first_commit=0.35)
                st += s["steps_executed"]; ac += s["accepted_steps"]; ev_n += len(ev); ps += sum(1 for _, p in ev if p)
            L.append(f"| {reg} | {rng} | {st/40:.1f} | {ac/40:.1f} | {ps/ev_n:.3f} |")
    L.append("")
    text = "\n".join(L)
    print(text)
    if args.write:
        with open(os.path.join(RESULTS_DIR, "reconcile_note.md"), "w", encoding="utf-8") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
