"""Compare the pre-registered analysis before and after aligning the engine (SYNTHETIC).

Before: experiments/results/pre_alignment/prereg_results.json (engine at 70dbad6:
RNG stream default_rng([seed, salt]), per-attempt ledger). After:
experiments/results/prereg_results.json (aligned engine: default_rng(seed +
10000007), two-forecast ledger). Same seeds, same code for everything else.
Usage: python -m experiments.compare_alignment [--write]
"""

from __future__ import annotations

import argparse
import json
import os
import sys

from experiments.injection_runs import RESULTS_DIR

OLD = os.path.join(RESULTS_DIR, "pre_alignment", "prereg_results.json")
NEW = os.path.join(RESULTS_DIR, "prereg_results.json")


def load(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def render(old: dict, new: dict) -> str:
    L = [
        "# Pre-registered analysis, before and after the engine alignment (SYNTHETIC)",
        "",
        "Generated by experiments/compare_alignment.py. 'Before' is the engine at 70dbad6 "
        "(per-attempt ledger, RNG default_rng([seed, salt])); 'after' is the aligned engine "
        "(two-forecast ledger, default_rng(seed + 10000007)). Same seeds. Mean differences are "
        "[95% bootstrap CI]; 'Holm reject' is the decision at family-wise 0.05.",
        "",
        "## Confirmatory family (12 tests)",
        "",
        "| id | regime | comparison | before: mean [CI] | before: Holm reject | after: mean [CI] | after: Holm reject | same sign | same decision |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    onew = {c["id"]: c for c in new["confirmatory"]}
    same_dec = 0
    for c in old["confirmatory"]:
        n = onew[c["id"]]
        same_sign = (c["mean"] > 0) == (n["mean"] > 0)
        same = c["reject_h0_at_0.05"] == n["reject_h0_at_0.05"]
        same_dec += same
        L.append(
            f"| {c['id']} | {c['regime']} | {c['comparison']} | {c['mean']:.4f} [{c['mean_ci'][0]:.4f}, {c['mean_ci'][1]:.4f}] "
            f"| {'yes' if c['reject_h0_at_0.05'] else 'no'} | {n['mean']:.4f} [{n['mean_ci'][0]:.4f}, {n['mean_ci'][1]:.4f}] "
            f"| {'yes' if n['reject_h0_at_0.05'] else 'no'} | {'yes' if same_sign else 'NO'} | {'yes' if same else 'NO'} |"
        )
    L += ["", f"Decisions unchanged in {same_dec} of {len(old['confirmatory'])} tests.", ""]
    L += [
        "## Per-regime descriptives",
        "",
        "| regime | pass rate before | pass rate after | mean steps injected before | after | mean accepted injected before | after | breaker open before | after |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r, ob in old["regimes"].items():
        nb = new["regimes"][r]
        L.append(
            f"| {r} | {ob['confirm_pass_rate']:.3f} | {nb['confirm_pass_rate']:.3f} | {ob['mean_steps']:.1f} | {nb['mean_steps']:.1f} "
            f"| {ob['mean_accepted']:.1f} | {nb['mean_accepted']:.1f} | {ob['breaker_open']['k']}/{ob['breaker_open']['n']} "
            f"| {nb['breaker_open']['k']}/{nb['breaker_open']['n']} |"
        )
    L += [
        "",
        "## Ledger score per run on the confirm seeds, mean (95% CIs are in the two tables files)",
        "",
        "Both scorings are recomputed offline from each version's events. The engine's own ledger is "
        "the two-forecast one after alignment and the per-attempt one before.",
        "",
        "| regime | policy | before: per-attempt | before: two-forecast | after: per-attempt | after: two-forecast |",
        "|---|---|---|---|---|---|",
    ]
    for r, ob in old["regimes"].items():
        nb = new["regimes"][r]
        for k in ob["ledger_per_run"]:
            L.append(
                f"| {r} | {k} | {ob['ledger_per_run'][k]['per_attempt_mean']:.1f} | {ob['ledger_per_run'][k]['two_forecast_mean']:.1f} "
                f"| {nb['ledger_per_run'][k]['per_attempt_mean']:.1f} | {nb['ledger_per_run'][k]['two_forecast_mean']:.1f} |"
            )
    L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = render(load(OLD), load(NEW))
    print(text)
    if args.write:
        with open(os.path.join(RESULTS_DIR, "alignment_comparison.md"), "w", encoding="utf-8") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
