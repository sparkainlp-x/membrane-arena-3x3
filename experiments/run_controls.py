"""Negative controls and prior sensitivity for the injection ledger (SYNTHETIC, exploratory).

Uses the confirm-seed runs already collected (experiments/results/runs_confirm.jsonl).
No new dynamics are run, so every control re-scores recorded events.
Usage: python -m experiments.run_controls [--write]

Controls
  coin    outcomes replaced by fair coin flips (generator seed 20261027). A fixed
          commit p has expected points -400 (p - 0.5)^2 <= 0 per forecast, so no
          policy may score above zero beyond noise.
  order   events permuted within each run (generator seed 20261028). Fixed
          policies ignore order, so their Brier and ledger must be unchanged
          (a check of the pipeline); the adaptive rule is order dependent.
Sensitivity
  prior   pseudo-count of the adaptive rule 0, 1, 4, 16, from 0.35 and 0.75.
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np

from experiments import rescoring as rs
from experiments import stats
from experiments.injection_runs import RESULTS_DIR, collect_set
from experiments.regimes import REGIMES
from experiments.run_prereg_analysis import dev_tuned_p, policies, runs_by_regime

COIN_SEED, ORDER_SEED = 20261027, 20261028


def mean_ci(x):
    e = stats.paired_effect(np.asarray(x, dtype=float))
    return f"{e['mean']:.3f} [{e['mean_ci'][0]:.3f}, {e['mean_ci'][1]:.3f}]"


def per_run(runs, policy, events_of, fn):
    return [fn(events_of(x), rs.policy_first_commits(events_of(x), policy)) for x in runs if events_of(x)]


def brier_mean(ev, firsts):
    return float(np.mean(rs.first_forecast_brier(ev, firsts)))


def points_first(ev, firsts):
    """Mean points of the first forecast per event (cost excluded); expected <= 0 under coin outcomes."""
    return float(np.mean([rs.calibration_points(p, passed) for (_, passed), p in zip(ev, firsts)]))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    dev = runs_by_regime(collect_set("dev"))
    conf = runs_by_regime(collect_set("confirm"))
    names = ("F35", "F75", "A35", "A75", "FT")
    L = ["# Negative controls and prior sensitivity (SYNTHETIC, exploratory; generated by experiments/run_controls.py)", "",
          "Confirm seeds, 100 runs per regime. Means per run with 95% bootstrap CIs over runs.", ""]

    # --- coin control
    L += ["## Control 1: fair coin outcomes (the ledger must not reward any policy)", "",
          "Mean first-forecast points per event (cost excluded; expected value for fixed p is -400 (p - 0.5)^2, i.e. F35 -9, F75 -25, FT near 0), and mean first-forecast Brier (expected 0.25 + (p - 0.5)^2).", "",
          "| regime | metric | " + " | ".join(names) + " | fixed 0.5 |", "|---|---|" + "---|" * (len(names) + 1)]
    for ri, reg in enumerate(REGIMES):
        pols = policies(dev_tuned_p(dev[reg])); pols["F50"] = {"kind": "fixed", "p": 0.5}
        rng = np.random.default_rng(COIN_SEED + ri)
        coin_runs = []
        for x in conf[reg]:
            ev = [[n, bool(rng.integers(0, 2))] for n, _ in x["events"]]
            coin_runs.append({"events": ev})
        for label, fn in (("points", points_first), ("Brier", brier_mean)):
            cells = [mean_ci(per_run(coin_runs, pols[k], lambda x: x["events"], fn)) for k in (*names, "F50")]
            L.append(f"| {reg} | {label} | " + " | ".join(cells) + " |")
    L.append("")

    # --- order control
    L += ["## Control 2: events permuted within each run", "",
          "Mean first-forecast Brier per run, real order versus permuted order. Fixed policies must be identical (pipeline check); the adaptive rule may change.", "",
          "| regime | policy | real order | permuted | difference (permuted - real) |", "|---|---|---|---|---|"]
    for ri, reg in enumerate(REGIMES):
        pols = policies(dev_tuned_p(dev[reg]))
        rng = np.random.default_rng(ORDER_SEED + ri)
        perm_runs = []
        for x in conf[reg]:
            ev = list(x["events"])
            order = rng.permutation(len(ev))
            perm_runs.append({"events": [ev[i] for i in order]})
        for k in names:
            real = per_run(conf[reg], pols[k], lambda x: x["events"], brier_mean)
            perm = per_run(perm_runs, pols[k], lambda x: x["events"], brier_mean)
            d = np.array(perm) - np.array(real)
            L.append(f"| {reg} | {k} | {mean_ci(real)} | {mean_ci(perm)} | {np.mean(d):.4f} |")
            if k in ("F35", "F75", "FT"):
                assert np.allclose(d, 0, atol=1e-12), "fixed policy changed under permutation"
    L.append("")

    # --- prior sensitivity
    L += ["## Sensitivity: pseudo-count of the adaptive rule", "",
          "Mean first-forecast Brier per run, pooled ECE (5 bins) and mean two-forecast ledger per run. Weight 0 uses the first commit only until the first event has been seen.", "",
          "| regime | start | weight | Brier | ECE | ledger per run, per-attempt | ledger per run, two-forecast |", "|---|---|---|---|---|---|---|"]
    for reg in REGIMES:
        for start in (0.35, 0.75):
            for w in (0, 1, 4, 16):
                pol = {"kind": "adaptive", "first": start, "weight": w}
                runs = [x for x in conf[reg] if x["events"]]
                br = per_run(runs, pol, lambda x: x["events"], brier_mean)
                fs = [rs.policy_first_commits(x["events"], pol) for x in runs]
                ys = [[int(o) for _, o in x["events"]] for x in runs]
                ece = stats.ece_with_ci(fs, ys, n_boot=1000)
                la = per_run(conf[reg], pol, lambda x: x["events"], rs.ledger_per_attempt)
                lt = per_run(conf[reg], pol, lambda x: x["events"], rs.ledger_two_forecast)
                L.append(f"| {reg} | {start} | {w} | {mean_ci(br)} | {ece['ece']:.3f} [{ece['ece_ci'][0]:.3f}, {ece['ece_ci'][1]:.3f}] | {np.mean(la):.1f} | {np.mean(lt):.1f} |")
    L.append("")
    text = "\n".join(L)
    print(text)
    if args.write:
        with open(os.path.join(RESULTS_DIR, "controls.md"), "w", encoding="utf-8") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
