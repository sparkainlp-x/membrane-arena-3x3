"""Build docs/RESULTS-injection.md from the measured files (SYNTHETIC).

Usage: python -m experiments.build_results [--write]

Every number in the generated file is read from, or computed from:
  experiments/results/prereg_results.json              (pre-registered analysis, aligned engine)
  experiments/results/pre_alignment/prereg_results.json (same analysis, engine before alignment)
  experiments/results/multiseed_runs.jsonl             (50-seed sweep, raw runs)
No number is typed by hand. ``tests/test_build_results.py`` checks that the
committed file equals this script's output. ``make results`` regenerates the
inputs first.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "experiments", "results")
OUT = os.path.join(ROOT, "docs", "RESULTS-injection.md")

# Prior expectations recorded in the pre-registration (section 6). None = no sign expectation.
EXPECT = {
    "C1": "+", "C2": "+", "C3": "+",
    "C4": "-", "C5": None, "C6": "+",
    "C7": "+ or none", "C8": "-", "C9": "-",
    "C10": "+ or none", "C11": "+ or none", "C12": "+ or none",
}
REGIMES = ("stock", "intermediate", "evolved")
POLICIES = ("F35", "F75", "A35", "A75", "FT")


def _load(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def _multiseed():
    spec = importlib.util.spec_from_file_location(
        "injection_multiseed", os.path.join(ROOT, "scripts", "injection_multiseed.py")
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    with open(os.path.join(RES, "multiseed_runs.jsonl"), encoding="utf-8") as fh:
        runs = sorted((json.loads(line) for line in fh), key=lambda r: r["seed"])
    return mod, runs


def f(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def ci(m, c, nd=1):
    return f"{m:.{nd}f} [{c[0]:.{nd}f}, {c[1]:.{nd}f}]"


def sign_ok(expect, mean):
    if expect is None:
        return "not judged by sign"
    if expect == "+":
        return "as expected" if mean > 0 else "SURPRISE"
    if expect == "-":
        return "as expected" if mean < 0 else "SURPRISE"
    return "within expectation" if mean >= 0 else "SURPRISE"


def render() -> str:
    new = _load(os.path.join(RES, "prereg_results.json"))
    old = _load(os.path.join(RES, "pre_alignment", "prereg_results.json"))
    ms, runs = _multiseed()
    env = new["environment"]
    seeds = new["seeds"]
    conf = new["confirmatory"]
    n_reject = sum(c["reject_h0_at_0.05"] for c in conf)
    onew = {c["id"]: c for c in conf}
    unchanged = sum(
        (c["mean"] > 0) == (onew[c["id"]]["mean"] > 0)
        and c["reject_h0_at_0.05"] == onew[c["id"]]["reject_h0_at_0.05"]
        for c in old["confirmatory"]
    )
    surprises = [c["id"] for c in conf if sign_ok(EXPECT[c["id"]], c["mean"]) == "SURPRISE"]

    lower = {
        r: min(("F35", "F75"), key=lambda k: new["regimes"][r]["calibration"][k]["ece"]) for r in REGIMES
    }
    c7 = onew["C7"]
    ece_line = (
        "Which of the two untuned fixed commits has the lower ECE: "
        + "; ".join(f"{r} {lower[r]}" for r in REGIMES)
        + ". A fixed commit is well calibrated only near its own regime's pass rate, so no fixed default is right "
        "in every regime. FT (fixed at the dev pass rate) is the benchmark that knows the rate in advance. "
        f"In the stock regime the adaptive rule's first-forecast Brier is {'higher' if c7['mean'] > 0 else 'lower'} "
        "than that of the fixed 0.35 commit (C7), which is the burn-in cost of not knowing the rate in advance."
    )
    L = [
        "# Results: Crystallize injection (SYNTHETIC)",
        "",
        "Generated by `experiments/build_results.py` from the measured files in `experiments/results/`; "
        "do not edit by hand (`make results` regenerates the inputs, `make results-offline` re-renders from the "
        "cached raw runs). Protocol: [PREREGISTRATION-injection.md](PREREGISTRATION-injection.md), including its "
        "Amendment A1. SYNTHETIC classical NumPy simulation of one toy model; nothing here is a physical claim. "
        f"Measured on Python {env['python']}, NumPy {env['numpy']}.",
        "",
        "## 1. What was run, and deviations from the protocol",
        "",
        f"- Engine: the aligned `MembraneArena3x3WithInjection` (two-forecast ledger, injection stream "
        "`default_rng(seed + 10000007)`). Regimes, seed sets (dev "
        f"{seeds['dev'][0]} to {seeds['dev'][1]}, confirm {seeds['confirm'][0]} to {seeds['confirm'][1]}, tuning "
        f"{', '.join(str(s) for s in seeds['tuning'])}), policies, the family of 12 tests, Holm correction and "
        "bootstrap settings are as pre-registered.",
        "- **Deviation 1 (Amendment A1).** The confirmatory run was first made on the engine before alignment "
        "(per-attempt ledger, stream `default_rng([seed, salt])`). After the author supplied the original module "
        "the engine was aligned on scoring and stream and the whole analysis was repeated on the same seeds "
        "(protocol section 7). Both outcomes are in the repository: the pre-alignment files are unchanged in "
        "`experiments/results/pre_alignment/`; the files in `experiments/results/` are the aligned run. "
        "Section 6 compares them.",
        "- **Deviation 2.** The primary descriptive ledger is the two-forecast scoring (Amendment A1). Both "
        "scorings are reported in section 4.",
        "- No other deviation. No seeds were added or removed after seeing results.",
        "",
        "## 2. Descriptives per regime (confirm seeds, 100 runs per regime)",
        "",
        "| regime | dev pass rate (events) | confirm pass rate (events) | FT commit | breaker open, injected (Wilson 95%) | breaker open, stock | mean steps stock | mean steps injected | mean accepted stock | mean accepted injected | runs without events |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in REGIMES:
        b = new["regimes"][r]
        bo = b["breaker_open"]
        L.append(
            f"| {r} | {f(b['dev_pass_rate'])} ({b['dev_events']}) | {f(b['confirm_pass_rate'])} ({b['confirm_events']}) "
            f"| {b['FT_p']:.2f} | {bo['k']}/{bo['n']} ({f(bo['wilson95'][0])} to {f(bo['wilson95'][1])}) "
            f"| {b['stock_breaker_open_k']}/{bo['n']} | {f(b['mean_stock_steps'], 1)} | {f(b['mean_steps'], 1)} "
            f"| {f(b['mean_stock_accepted'], 1)} | {f(b['mean_accepted'], 1)} | {b['runs_without_events']} |"
        )
    all_open = all(new["regimes"][r]["breaker_open"]["k"] == new["regimes"][r]["breaker_open"]["n"] for r in REGIMES)
    L += [
        "",
        ("**The injection does not cure the breaker:** the breaker was open at the end of every injected run in "
         "every regime, exactly as in the stock engine." if all_open else
         "The breaker was not open at the end of every injected run; see the table."),
        "",
        "## 3. Confirmatory family (12 tests, Holm), confirm seeds",
        "",
        "Paired by seed, two-sided paired sign-flip permutation test (100,000 flips), Holm over the 12 p-values, "
        "family-wise level 0.05. Mean paired difference and dz with 95% percentile bootstrap intervals (10,000 "
        "resamples of seeds); the intervals are not adjusted for multiplicity.",
        "",
        "| id | regime | comparison | mean difference [95% CI] | dz [95% CI] | p (sign-flip) | p Holm | reject at 0.05 | prior expectation | observed vs expectation |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for c in conf:
        dz = "n/a" if c["dz"] is None else f"{c['dz']:.2f} [{f(c['dz_ci'][0], 2)}, {f(c['dz_ci'][1], 2)}]"
        L.append(
            f"| {c['id']} | {c['regime']} | {c['comparison']} | {c['mean']:.4f} [{c['mean_ci'][0]:.4f}, {c['mean_ci'][1]:.4f}] "
            f"| {dz} | {c['p']:.5f} | {c['p_holm']:.5f} | {'yes' if c['reject_h0_at_0.05'] else 'no'} "
            f"| {EXPECT[c['id']] or 'small'} | {sign_ok(EXPECT[c['id']], c['mean'])} |"
        )
    L += [
        "",
        f"Decisions: the null hypothesis was rejected in {n_reject} of {len(conf)} tests. "
        + ("Every observed sign agreed with the recorded prior expectation, except where no sign was expected (C5)."
           if not surprises else f"Observed signs that contradicted the prior expectation: {', '.join(surprises)}."),
        "These are statements about differences between these policies on this toy model's confirm seeds. The "
        "p-values sit at the permutation floor ((0 + 1) / (100,000 + 1)) wherever the effect is large, so the "
        "size of an effect should be read from the mean difference and dz, not from p.",
        "",
        "Mean first-forecast Brier per run (lower is better):",
        "",
        "| regime | F35 | F75 | A35 | A75 | FT |",
        "|---|---|---|---|---|---|",
    ]
    for r in REGIMES:
        m = new["regimes"][r]["mean_first_forecast_brier"]
        L.append(f"| {r} | " + " | ".join(f"{m[k]:.4f}" for k in POLICIES) + " |")
    L += [
        "",
        "Pooled expected calibration error (5 bins; cluster bootstrap 95% CI over runs):",
        "",
        "| regime | F35 | F75 | A35 | A75 | FT |",
        "|---|---|---|---|---|---|",
    ]
    for r in REGIMES:
        c = new["regimes"][r]["calibration"]
        L.append(f"| {r} | " + " | ".join(f"{c[k]['ece']:.3f} [{c[k]['ece_ci'][0]:.3f}, {c[k]['ece_ci'][1]:.3f}]" for k in POLICIES) + " |")
    L += [
        "",
        ece_line,
        "",
        "## 4. Ledger score per run, both scorings (exploratory), confirm seeds",
        "",
        "Mean [95% bootstrap CI over runs]. Two-forecast is the engine's scoring and the primary descriptive ledger "
        "(Amendment A1); per-attempt (every variant scored, cost not subtracted) is the original merged version, "
        "recomputed offline from the same events.",
        "",
        "| regime | scoring | F35 | F75 | A35 | A75 | FT |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in REGIMES:
        b = new["regimes"][r]
        for label, key in (("two-forecast (primary)", "two_forecast"), ("per-attempt", "per_attempt")):
            L.append(
                f"| {r} | {label} | "
                + " | ".join(ci(b["ledger_per_run"][k][key + "_mean"], b["ledger_per_run"][k][key + "_ci"]) for k in POLICIES)
                + " |"
            )
    stock35 = new["regimes"]["stock"]["ledger_per_run"]["F35"]
    L += [
        "",
        f"Null result: in the stock regime the two-forecast score of the fixed 0.35 commit is "
        f"{ci(stock35['two_forecast_mean'], stock35['two_forecast_ci'])} per run, an interval that "
        + ("includes zero" if stock35["two_forecast_ci"][0] <= 0 <= stock35["two_forecast_ci"][1] else "excludes zero")
        + ". The sign of a policy's ledger score depends on the scoring rule (compare the two rows of each regime).",
        "",
        "Tuning seeds (in-sample; total ledger over the 5 tuning runs):",
        "",
        "| regime | scoring | F35 | F75 | A35 | A75 | FT |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in REGIMES:
        t = new["regimes"][r]["tuning_seeds_total_ledger"]
        for label, key in (("two-forecast", "two_forecast"), ("per-attempt", "per_attempt")):
            L.append(f"| {r} | {label} | " + " | ".join(f"{t[k][key]:.1f}" for k in POLICIES) + " |")
    L += [
        "",
        "Steps executed, injection minus none (confirm seeds, mean [95% CI]):",
        "",
    ]
    for r in REGIMES:
        e = new["regimes"][r]["steps_diff"]
        L.append(f"- {r}: {e['mean']:.2f} [{e['mean_ci'][0]:.2f}, {e['mean_ci'][1]:.2f}]")
    L += [
        "",
        "## 5. Seeds 0 to 49 (stock regime), default setting and dt-only ablation",
        "",
        "Generated by `scripts/injection_multiseed.py`; the same section, with its own limits, is in "
        "[injection_results.md](injection_results.md). Raw per-seed runs: "
        "[../experiments/results/multiseed_runs.jsonl](../experiments/results/multiseed_runs.jsonl).",
        "",
        ms.render(runs).replace("## Multi-seed sweep", "### Multi-seed sweep", 1).replace("\n### ", "\n#### "),
        "",
        "## 6. Before and after the engine alignment",
        "",
        f"Same seeds, same analysis code: the direction and the Holm decision are unchanged in {unchanged} of "
        f"{len(old['confirmatory'])} confirmatory tests. The test-by-test table, the per-regime descriptives and the "
        "ledger means under both scorings are in "
        "[../experiments/results/alignment_comparison.md](../experiments/results/alignment_comparison.md). "
        "The pre-alignment raw runs and outputs are kept unchanged in `experiments/results/pre_alignment/`.",
        "",
        "## 7. Other measured files (not part of the confirmatory family)",
        "",
        "- Negative controls (fair-coin outcomes, events permuted within runs) and the sensitivity to the adaptive "
        "rule's pseudo-count: [../experiments/results/controls.md](../experiments/results/controls.md).",
        "- Event layout inside runs (the last events of every run are failures by construction): "
        "[../experiments/results/event_structure.md](../experiments/results/event_structure.md).",
        "- Reconciliation with the design note's table: "
        "[../experiments/results/reconcile_note.md](../experiments/results/reconcile_note.md).",
        "- The true phase damping experiment (not part of this analysis, and it does not use the injection): "
        "[../experiments/results/phase_damping.md](../experiments/results/phase_damping.md).",
        "- Full console output of the pre-registered analysis, including reliability tables: "
        "[../experiments/results/prereg_tables.md](../experiments/results/prereg_tables.md); machine-readable: "
        "[../experiments/results/prereg_results.json](../experiments/results/prereg_results.json).",
        "- Raw runs: `experiments/results/runs_dev.jsonl`, `runs_confirm.jsonl`, `runs_tuning.jsonl`.",
        "",
        "## 8. Honest limits",
        "",
        "- One toy model (a synthetic 3x3 lattice of 32-dimensional density matrices), three synthetic parameter "
        "sets, one machine, one NumPy. Nothing here says anything about a physical system or about any other model.",
        "- The forecasts do not use event features, so the ledger measures calibration to a base rate, not "
        "event-level discrimination.",
        "- The sign of a ledger score depends on the scoring rule: the same events give different signs under the "
        "two scorings (section 4). The ledger is a descriptive metric, not an outcome measure.",
        "- The five tuning seeds (42, 0, 1, 2, 3) are inside the seeds 0 to 49 of section 5, and the 0.35 default "
        "was chosen on them, so section 5's 0.35 rows and the tuning-seed totals are partly or wholly in-sample. "
        "The confirm seeds are disjoint from them.",
        "- Events within a run are not independent and the last events of every run are failures by construction "
        "(the breaker needs consecutive rejections), so pooled pass rates are descriptive; the intervals resample "
        "seeds or runs, not events.",
        "- The \"evolved\" regime is the genome supplied with the design note, used as given; it was not re-evolved. "
        "The \"intermediate\" regime is the arithmetic midpoint of the other two, fixed by definition.",
        "- The prior expectations in section 3 were recorded before the run so that a surprise is visible; they did "
        "not change the two-sided tests.",
        "- The injection does not change the guards, the thresholds or the breaker, and it does not cure the arena.",
        "",
        "## 9. Reproduce",
        "",
        "```bash",
        "make results           # or: python scripts/reproduce_results.py            (re-collect every raw run, re-run every analysis, rebuild this file; tens of minutes on one core)",
        "make results-offline   # or: python scripts/reproduce_results.py --offline  (re-run the analyses from the cached raw runs and rebuild this file; seconds)",
        "```",
        "",
        "`OMP_NUM_THREADS=1` is set by the script. Raw runs are deterministic for a fixed NumPy.",
        "",
    ]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.write:
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write(text)
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
